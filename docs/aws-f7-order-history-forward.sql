begin;
set local lock_timeout = '5s';
set local statement_timeout = '30s';

do $guard$
begin
  if current_user <> 'hod_migration' then raise exception 'Expected hod_migration'; end if;
  if to_regclass('public.order_status_history') is not null then
    raise exception 'order_status_history already exists; inspect before retry';
  end if;
  if exists (select 1 from pg_trigger where tgrelid = 'public.orders'::regclass
    and tgname = 'orders_record_status_history' and not tgisinternal) then
    raise exception 'Order history trigger already exists';
  end if;
  if to_regprocedure('public.record_order_status_history()') is not null then
    raise exception 'Order history function already exists';
  end if;
end $guard$;

create table public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  status text not null,
  created_at timestamptz not null default now()
);
create index order_status_history_order_created_idx
  on public.order_status_history(order_id, created_at asc);
alter table public.order_status_history enable row level security;
revoke all on public.order_status_history from public, anon, authenticated;
grant select on public.order_status_history to hod_app;
create policy hod_app_f7_order_history_select on public.order_status_history
  for select to hod_app using (true);

create function public.record_order_status_history()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into public.order_status_history(order_id, status)
    values (new.id, coalesce(nullif(trim(new.status::text), ''), 'pending'));
  end if;
  return new;
end;
$$;
revoke all on function public.record_order_status_history() from public, anon, authenticated;
create trigger orders_record_status_history
  after insert or update of status on public.orders
  for each row execute function public.record_order_status_history();

insert into public.order_status_history(order_id, status, created_at)
select o.id, coalesce(nullif(trim(o.status::text), ''), 'pending'), o.created_at
from public.orders o
where not exists (select 1 from public.order_status_history h where h.order_id = o.id);
commit;
